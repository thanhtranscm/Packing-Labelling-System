import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
await fs.mkdir('.sites-runtime',{recursive:true});
await fs.writeFile('.sites-runtime/check-render-state.mjs',ts.transpileModule(await fs.readFile('lib/render-state.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {shareUnchanged}=await import('../.sites-runtime/check-render-state.mjs');
const old={items:[{id:'a',qty:1}],months:[{id:'sep',orders:[{id:'po',qty:6}]}]};
assert.equal(shareUnchanged(old,structuredClone(old)),old);
const next=structuredClone(old);next.items[0].qty=2;
const result=shareUnchanged(old,next);
assert.deepEqual(result,next);assert.equal(result.months,old.months);assert.notEqual(result.items,old.items);assert.equal(old.items[0].qty,1);
const deleted={...next,months:[]};assert.deepEqual(shareUnchanged(old,deleted),deleted);
assert.deepEqual(shareUnchanged({a:undefined},{b:undefined}),{b:undefined});
assert.deepEqual(shareUnchanged([1,2],[2,1]),[2,1]);
console.log('Render state: identical response, changed values, preserved PO references, deletion, key replacement and reordering passed.');
const {existingSelection}=await import('../.sites-runtime/check-render-state.mjs');
const selected=['a','removed','b'];assert.deepEqual(existingSelection(selected,new Set(['a','b'])),['a','b']);
assert.deepEqual(existingSelection(selected,new Set()),[]);assert.equal(existingSelection(selected,new Set(selected)),selected);
assert.deepEqual(selected,['a','removed','b']);
const ids=Array.from({length:20000},(_,i)=>String(i));assert.equal(existingSelection(ids,new Set(ids)),ids);
console.log('Processed PO selection: deletes/clear remove stale IDs, stable references and 20,000 rows passed.');
